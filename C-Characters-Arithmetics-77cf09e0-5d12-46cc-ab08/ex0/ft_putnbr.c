#include <unistd.h>

void	ft_putnbr(int nb)
{
	int		c;
	char	t[15];

	c = 0;
	if (nb == 0)
		write(1, "0", 1);
	else if (nb == -2147483648)
		write(1, "-2147483648", 11);
	else if (nb < 0)
	{
		write(1, "-", 1);
		nb = -nb;
	}
	while (nb > 0)
	{
		t[c] = (nb % 10) + '0';
		nb /= 10;
		c++;
	}
	while (c > 0)
	{
		c--;
		write(1, &t[c], 1);
	}
}
